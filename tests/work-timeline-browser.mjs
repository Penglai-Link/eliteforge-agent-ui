/** Shared React/Vue acceptance; invoked through Playwright CLI. */
export async function verifyWorkTimeline(page, { url, name }) {
  const checks = [], check = (label, value) => { if (!value) throw new Error(label); checks.push(label); };
  await page.goto(url);
  const work = page.getByRole("region", { name: "Agent work", exact: true });
  await work.getByText("先检查目录结构。", { exact: true }).waitFor();
  const rows = () => work.locator("[data-work-item]").evaluateAll(nodes => nodes.map(node => node.dataset.workItem));
  check("working process is expanded without a toggle", await work.locator(".ef-chat__rail-summary[aria-expanded]").count() === 0);
  check("reasoning and first output appear in source order", JSON.stringify(await rows()) === JSON.stringify(["reasoning", "message"]));
  const status = work.getByRole("status");
  check("fixed working label is last", await status.textContent() === "工作中" && await status.evaluate(node => node === node.parentElement.lastElementChild));
  check("working label pulses", await status.locator("span").evaluate(node => getComputedStyle(node).animationName === "ef-chat-working"));
  await page.locator('[data-message-id="step-1"]').evaluate(node => { window.__firstStep = node; });
  await page.getByRole("button", { name: "Next phase", exact: true }).click();
  await work.getByText("步骤2的输出：模块边界已确认。", { exact: true }).waitFor();
  check("thoughts, outputs and tools stay interleaved", JSON.stringify(await rows()) === JSON.stringify(["reasoning", "message", "tool", "reasoning", "message"]));
  check("prior step retains its own card while streaming", await page.locator('[data-message-id="step-1"]').evaluate(node => node === window.__firstStep));
  check("single tool is visible without a group toggle", await work.getByRole("button", { name: /Shell pwd/ }).isVisible() && await work.locator('.ef-chat__rail-entry-toggle').count() === 0);
  await page.screenshot({ path: `output/playwright/work-timeline-${name}-working.png`, animations: "disabled" });
  await page.getByRole("button", { name: "Next phase", exact: true }).click();
  await work.getByText("最终回答：目录和模块边界检查完成。", { exact: true }).waitFor();
  check("text end alone does not fold a running process", await status.isVisible());
  await page.getByRole("button", { name: "Next phase", exact: true }).click();
  const summary = work.getByRole("button", { name: /工作完成/ });
  await summary.waitFor();
  check("success collapses all process cards", await summary.getAttribute("aria-expanded") === "false" && await work.locator("[data-work-item]").count() === 0);
  check("working label disappears after success", await work.getByRole("status").count() === 0);
  const final = page.locator('[data-message-id="final"]');
  check("final is a separate visible card", await final.isVisible() && await final.evaluate(node => !node.closest('[aria-label="Agent work"]')));
  check("earlier outputs are included in the collapsed process", await page.locator('[data-message-id="step-1"], [data-message-id="step-2"]').count() === 0);
  await page.screenshot({ path: `output/playwright/work-timeline-${name}-final.png`, animations: "disabled" });
  await summary.click();
  check("one toggle restores the full ordered process", JSON.stringify(await rows()) === JSON.stringify(["reasoning", "message", "tool", "reasoning", "message", "reasoning"]));
  check("expanded process does not duplicate the final answer", await final.count() === 1);
  await page.getByRole("button", { name: "Restore history", exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.ef-chat__rail-summary[aria-expanded="false"]'));
  check("restored history starts folded with a separate final", await final.isVisible() && await page.locator('[data-message-id="step-1"]').count() === 0);
  await summary.click();
  check("history preserves reasoning, outputs and tool order", JSON.stringify(await rows()) === JSON.stringify(["reasoning", "message", "tool", "reasoning", "message", "reasoning"]));
  await work.getByRole("button", { name: /Shell pwd/ }).click();
  await work.getByText("/workspace/Tron", { exact: true }).waitFor();
  check("restored tool result remains accessible", await work.getByText("/workspace/Tron", { exact: true }).isVisible());
  return { name, passed: checks.length, checks };
}
